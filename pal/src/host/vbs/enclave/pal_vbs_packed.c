/*
 * Loader for the packed objects of this enclave image (phase 2, refinement (a') of PLAN.md D2).
 *
 * What it does. scripts/vbs/pack.py embedded, at build time, the load image of each AArch64 Linux
 * shared object verbatim (every PT_LOAD at its p_vaddr, BSS as zeros) into the `.gxpack` section of
 * this signed enclave image, and generated `pal_vbs_packed_table.h` (name, offset, entry, ...).
 * Since every image is intact, the PC-relative distances the compiler baked into the object still
 * hold at its in-image base. What remains is what a dynamic loader does for a shared object that is
 * already in memory:
 *
 *   1. validate the ELF header and program headers of the in-image copy;
 *   2. validate every dynamic relocation (type, target, symbol) BEFORE writing anything;
 *   3. make the object's own writable PT_LOAD pages read-write with VirtualProtect -- the one-way
 *      change from the image's execute-read protection that the platform allows (phase 0, step c);
 *   4. apply the relocations in place (the four AArch64 types Gramine's own loaders handle:
 *      R_AARCH64_RELATIVE, R_AARCH64_ABS64, R_AARCH64_GLOB_DAT, R_AARCH64_JUMP_SLOT), binding
 *      undefined symbols to the table of functions the enclave offers (the PAL's exports);
 *   5. make the PT_GNU_RELRO pages read-only again, and return the entry address.
 *
 * What it cannot do, by construction. VBS enclaves forbid making any memory executable at run time
 * (phase 0, step c: every execute protection fails with 1655), so the only code that can ever run
 * is code that was in the signed image at build time. This loader never asks for an execute
 * protection; the only protection it requests is PAGE_READWRITE for an object's writable segments
 * and PAGE_READONLY for its RELRO part. Writes go only into those writable segments.
 *
 * Strict W^X and blocker 4. Executing a non-executable page, or writing an executable image page,
 * hangs the enclave thread instead of raising an exception (phase 0, step c). So: (a) a writable
 * segment whose pages overlap a page of an executable segment is refused (making that page RW would
 * make code on it unusable); (b) no relocation target outside the writable segments is accepted, so
 * nothing ever writes an executable page; (c) the returned entry must lie in an executable segment.
 */

#include <winenclave.h>
#include <stdint.h>
#include <string.h>

#include "pal_vbs_packed.h"
#include "pal_vbs_packed_table.h" /* generated by scripts/vbs/pack.py */

/* the packed blob: one executable section of the image (pal_vbs_packed_blob.S, generated) */
extern const uint8_t g_pal_vbs_packed_blob[];
/* the original bytes of the packed files: read-only data (same generated file) */
extern const uint8_t g_pal_vbs_packed_files[];

#define VBS_PAGE 0x1000ull

/* ---- minimal ELF64 definitions (the Windows headers have none) ---- */

typedef struct {
    uint8_t  e_ident[16];
    uint16_t e_type, e_machine;
    uint32_t e_version;
    uint64_t e_entry, e_phoff, e_shoff;
    uint32_t e_flags;
    uint16_t e_ehsize, e_phentsize, e_phnum, e_shentsize, e_shnum, e_shstrndx;
} vbs_elf64_ehdr;

typedef struct {
    uint32_t p_type, p_flags;
    uint64_t p_offset, p_vaddr, p_paddr, p_filesz, p_memsz, p_align;
} vbs_elf64_phdr;

typedef struct {
    int64_t  d_tag;
    uint64_t d_val;
} vbs_elf64_dyn;

typedef struct {
    uint32_t st_name;
    uint8_t  st_info, st_other;
    uint16_t st_shndx;
    uint64_t st_value, st_size;
} vbs_elf64_sym;

typedef struct {
    uint64_t r_offset, r_info;
    int64_t  r_addend;
} vbs_elf64_rela;

#define ET_DYN        3
#define EM_AARCH64    183
#define PT_LOAD       1
#define PT_DYNAMIC    2
#define PT_TLS        7
#define PT_GNU_RELRO  0x6474e552
#define PF_X          1
#define PF_W          2

#define DT_NULL       0
#define DT_PLTRELSZ   2
#define DT_HASH       4
#define DT_STRTAB     5
#define DT_SYMTAB     6
#define DT_RELA       7
#define DT_RELASZ     8
#define DT_RELAENT    9
#define DT_STRSZ      10
#define DT_SYMENT     11
#define DT_REL        17
#define DT_PLTREL     20
#define DT_TEXTREL    22
#define DT_JMPREL     23
#define DT_GNU_HASH   0x6ffffef5

#define SHN_UNDEF     0
#define STB_WEAK      2
#define STT_TLS       6
#define STT_GNU_IFUNC 10

#define R_AARCH64_NONE      0
#define R_AARCH64_ABS64     257
#define R_AARCH64_GLOB_DAT  1025
#define R_AARCH64_JUMP_SLOT 1026
#define R_AARCH64_RELATIVE  1027

#define MAX_SEGS 16

/* everything known about one object while it is being prepared */
struct pk_obj {
    const struct pal_vbs_packed_obj* row;
    uint8_t* base;
    uint64_t size;
    /* page-granular ranges, offsets from base */
    uint64_t wr_lo[MAX_SEGS], wr_hi[MAX_SEGS]; /* writable PT_LOADs, exact (not page-rounded) */
    uint64_t nwr;
    uint64_t x_lo[MAX_SEGS], x_hi[MAX_SEGS];   /* executable PT_LOADs, exact */
    uint64_t nx;
    uint64_t relro_lo, relro_hi;               /* page-rounded as ld.so does; 0,0 if none */
    uint64_t dyn_off, dyn_size;
    /* from the dynamic section, offsets from base */
    uint64_t rela, relasz, jmprel, pltrelsz, symtab, strtab, strsz, hash, gnu_hash;
};

static uint8_t g_loaded[PAL_VBS_PACKED_COUNT];

static uint64_t page_down(uint64_t x) { return x & ~(VBS_PAGE - 1); }
static uint64_t page_up(uint64_t x) { return (x + VBS_PAGE - 1) & ~(VBS_PAGE - 1); }

/* [off, off+len) lies inside the object's load image (overflow-safe) */
static int in_image(const struct pk_obj* o, uint64_t off, uint64_t len) {
    return off <= o->size && len <= o->size - off;
}

/* [off, off+len) lies inside one writable segment */
static int in_writable(const struct pk_obj* o, uint64_t off, uint64_t len) {
    for (uint64_t i = 0; i < o->nwr; i++)
        if (off >= o->wr_lo[i] && off < o->wr_hi[i] && len <= o->wr_hi[i] - off)
            return 1;
    return 0;
}

/* [off, off+len) lies inside one executable segment */
static int in_executable(const struct pk_obj* o, uint64_t off, uint64_t len) {
    for (uint64_t i = 0; i < o->nx; i++)
        if (off >= o->x_lo[i] && off - o->x_lo[i] < o->x_hi[i] - o->x_lo[i] &&
            len <= o->x_hi[i] - off)
            return 1;
    return 0;
}

static const char* str_at(const struct pk_obj* o, uint64_t idx) {
    if (idx >= o->strsz)
        return NULL;
    /* the string must be terminated inside the string table */
    const char* s = (const char*)o->base + o->strtab + idx;
    if (!memchr(s, 0, (size_t)(o->strsz - idx)))
        return NULL;
    return s;
}

/* ---- step 1: headers ---- */

static int64_t parse_headers(struct pk_obj* o, uint64_t* detail) {
    const vbs_elf64_ehdr* eh = (const vbs_elf64_ehdr*)o->base;
    if (!in_image(o, 0, sizeof(*eh)) || memcmp(eh->e_ident, "\177ELF", 4) != 0 ||
        eh->e_ident[4] != 2 /* ELFCLASS64 */ || eh->e_ident[5] != 1 /* little endian */ ||
        eh->e_type != ET_DYN || eh->e_machine != EM_AARCH64 ||
        eh->e_phentsize != sizeof(vbs_elf64_phdr) ||
        !in_image(o, eh->e_phoff, (uint64_t)eh->e_phnum * sizeof(vbs_elf64_phdr))) {
        *detail = 0;
        return PAL_VBS_PK_BADELF;
    }
    const vbs_elf64_phdr* ph = (const vbs_elf64_phdr*)(o->base + eh->e_phoff);
    for (uint16_t i = 0; i < eh->e_phnum; i++) {
        const vbs_elf64_phdr* p = &ph[i];
        if (p->p_type == PT_LOAD) {
            if (!in_image(o, p->p_vaddr, p->p_memsz) || p->p_filesz > p->p_memsz) {
                *detail = p->p_vaddr;
                return PAL_VBS_PK_LAYOUT;
            }
            if ((p->p_flags & PF_W) && (p->p_flags & PF_X)) {
                *detail = p->p_vaddr; /* a writable and executable segment cannot exist here */
                return PAL_VBS_PK_LAYOUT;
            }
            if (p->p_flags & PF_W) {
                if (o->nwr == MAX_SEGS) { *detail = p->p_vaddr; return PAL_VBS_PK_BADELF; }
                o->wr_lo[o->nwr] = p->p_vaddr;
                o->wr_hi[o->nwr] = p->p_vaddr + p->p_memsz;
                o->nwr++;
            } else if (p->p_flags & PF_X) {
                if (o->nx == MAX_SEGS) { *detail = p->p_vaddr; return PAL_VBS_PK_BADELF; }
                o->x_lo[o->nx] = p->p_vaddr;
                o->x_hi[o->nx] = p->p_vaddr + p->p_memsz;
                o->nx++;
            }
        } else if (p->p_type == PT_DYNAMIC) {
            o->dyn_off = p->p_vaddr;
            o->dyn_size = p->p_memsz;
        } else if (p->p_type == PT_GNU_RELRO) {
            o->relro_lo = page_down(p->p_vaddr);
            o->relro_hi = page_down(p->p_vaddr + p->p_memsz);
        } else if (p->p_type == PT_TLS) {
            /* TLS of packed objects is the LibOS's business (it sets up its own TCB); the PAL's
             * loader supports no TLS relocations, so nothing to do here. */
        }
    }
    if (!o->nx || !o->dyn_off || !in_image(o, o->dyn_off, o->dyn_size)) {
        *detail = o->dyn_off;
        return PAL_VBS_PK_BADELF;
    }
    if (o->row->dynamic_vaddr != o->dyn_off) {
        *detail = o->dyn_off; /* the packer's table and the image disagree */
        return PAL_VBS_PK_BADELF;
    }

    /* Strict W^X: no page of a writable segment may also hold executable bytes. */
    for (uint64_t w = 0; w < o->nwr; w++) {
        uint64_t wlo = page_down(o->wr_lo[w]), whi = page_up(o->wr_hi[w]);
        for (uint64_t x = 0; x < o->nx; x++) {
            uint64_t xlo = page_down(o->x_lo[x]), xhi = page_up(o->x_hi[x]);
            if (wlo < xhi && xlo < whi) {
                *detail = o->wr_lo[w];
                return PAL_VBS_PK_LAYOUT;
            }
        }
    }
    /* RELRO must be inside the writable segments (it is the start of the data segment). */
    if (o->relro_hi > o->relro_lo) {
        int inside = 0;
        for (uint64_t w = 0; w < o->nwr; w++)
            if (page_down(o->wr_lo[w]) <= o->relro_lo && o->relro_hi <= page_up(o->wr_hi[w]))
                inside = 1;
        if (!inside) {
            *detail = o->relro_lo;
            return PAL_VBS_PK_LAYOUT;
        }
    }
    return PAL_VBS_PK_OK;
}

static int64_t parse_dynamic(struct pk_obj* o, uint64_t* detail) {
    const vbs_elf64_dyn* d = (const vbs_elf64_dyn*)(o->base + o->dyn_off);
    uint64_t n = o->dyn_size / sizeof(*d);
    uint64_t relaent = sizeof(vbs_elf64_rela), syment = sizeof(vbs_elf64_sym), pltrel = DT_RELA;
    for (uint64_t i = 0; i < n && d[i].d_tag != DT_NULL; i++) {
        switch (d[i].d_tag) {
            case DT_RELA:     o->rela = d[i].d_val; break;
            case DT_RELASZ:   o->relasz = d[i].d_val; break;
            case DT_RELAENT:  relaent = d[i].d_val; break;
            case DT_JMPREL:   o->jmprel = d[i].d_val; break;
            case DT_PLTRELSZ: o->pltrelsz = d[i].d_val; break;
            case DT_PLTREL:   pltrel = d[i].d_val; break;
            case DT_SYMTAB:   o->symtab = d[i].d_val; break;
            case DT_SYMENT:   syment = d[i].d_val; break;
            case DT_STRTAB:   o->strtab = d[i].d_val; break;
            case DT_STRSZ:    o->strsz = d[i].d_val; break;
            case DT_HASH:     o->hash = d[i].d_val; break;
            case DT_GNU_HASH: o->gnu_hash = d[i].d_val; break;
            case DT_REL:      /* AArch64 uses RELA only */
            case DT_TEXTREL:  /* relocations in text would need writes to executable pages */
                *detail = (uint64_t)d[i].d_tag;
                return PAL_VBS_PK_BADELF;
            default: break;
        }
    }
    if (relaent != sizeof(vbs_elf64_rela) || syment != sizeof(vbs_elf64_sym) ||
        (o->pltrelsz && pltrel != DT_RELA) ||
        (o->relasz && !in_image(o, o->rela, o->relasz)) ||
        (o->pltrelsz && !in_image(o, o->jmprel, o->pltrelsz)) ||
        !o->strtab || !in_image(o, o->strtab, o->strsz) ||
        !o->symtab || !in_image(o, o->symtab, sizeof(vbs_elf64_sym))) {
        *detail = o->dyn_off;
        return PAL_VBS_PK_BADELF;
    }
    return PAL_VBS_PK_OK;
}

/* ---- symbols ---- */

static const vbs_elf64_sym* sym_at(const struct pk_obj* o, uint64_t idx) {
    /* the dynamic symbol table has no size in the dynamic section; bound by the image */
    if (idx > (o->size - o->symtab) / sizeof(vbs_elf64_sym) - 1)
        return NULL;
    return (const vbs_elf64_sym*)(o->base + o->symtab) + idx;
}

static uint32_t sysv_hash(const char* s) {
    uint32_t h = 0, g;
    for (; *s; s++) {
        h = (h << 4) + (uint8_t)*s;
        g = h & 0xf0000000u;
        if (g)
            h ^= g >> 24;
        h &= ~g;
    }
    return h;
}

static uint32_t gnu_hash(const char* s) {
    uint32_t h = 5381;
    for (; *s; s++)
        h = h * 33 + (uint8_t)*s;
    return h;
}

static int sym_matches(const struct pk_obj* o, const vbs_elf64_sym* s, const char* name) {
    if (!s || s->st_shndx == SHN_UNDEF)
        return 0;
    const char* n = str_at(o, s->st_name);
    return n && strcmp(n, name) == 0;
}

/* a defined dynamic symbol of the object, via DT_GNU_HASH or DT_HASH; NULL if absent */
static const vbs_elf64_sym* find_defined(const struct pk_obj* o, const char* name) {
    if (o->gnu_hash && in_image(o, o->gnu_hash, 16)) {
        const uint32_t* h = (const uint32_t*)(o->base + o->gnu_hash);
        uint32_t nbuckets = h[0], symoffset = h[1], bloom_size = h[2];
        uint64_t hdr = 16 + (uint64_t)bloom_size * 8;
        if (nbuckets && in_image(o, o->gnu_hash, hdr + (uint64_t)nbuckets * 4)) {
            const uint32_t* buckets = (const uint32_t*)(o->base + o->gnu_hash + hdr);
            const uint32_t* chain = buckets + nbuckets;
            uint32_t hv = gnu_hash(name);
            uint32_t idx = buckets[hv % nbuckets];
            if (idx < symoffset)
                return NULL;
            for (;; idx++) {
                uint64_t coff = o->gnu_hash + hdr + ((uint64_t)nbuckets + (idx - symoffset)) * 4;
                if (!in_image(o, coff, 4))
                    return NULL;
                uint32_t h2 = chain[idx - symoffset];
                const vbs_elf64_sym* s = sym_at(o, idx);
                if ((h2 | 1) == (hv | 1) && sym_matches(o, s, name))
                    return s;
                if (h2 & 1)
                    return NULL;
            }
        }
    }
    if (o->hash && in_image(o, o->hash, 8)) {
        const uint32_t* h = (const uint32_t*)(o->base + o->hash);
        uint32_t nbucket = h[0], nchain = h[1];
        if (!nbucket || !in_image(o, o->hash, 8 + ((uint64_t)nbucket + nchain) * 4))
            return NULL;
        const uint32_t* bucket = h + 2;
        const uint32_t* chain = bucket + nbucket;
        uint64_t steps = 0;
        for (uint32_t i = bucket[sysv_hash(name) % nbucket]; i && i < nchain && steps++ <= nchain;
             i = chain[i]) {
            const vbs_elf64_sym* s = sym_at(o, i);
            if (sym_matches(o, s, name))
                return s;
        }
    }
    return NULL;
}

/* ---- step 2 and 4: relocations ---- */

/*
 * Resolve the value S of relocation symbol `symidx`. A defined symbol resolves inside the object
 * (base + st_value); an undefined one is looked up in the enclave's import table. Returns 0 and
 * sets *value on success.
 */
static int64_t resolve_sym(const struct pk_obj* o, uint64_t symidx, const struct pal_vbs_import* imp,
                           uint64_t nimp, uint64_t* value, uint64_t* nbound, uint64_t* detail) {
    const vbs_elf64_sym* s = sym_at(o, symidx);
    if (!s) {
        *detail = symidx;
        return PAL_VBS_PK_BADELF;
    }
    uint8_t type = s->st_info & 0xf, bind = s->st_info >> 4;
    if (type == STT_TLS || type == STT_GNU_IFUNC) {
        *detail = symidx; /* neither is used by the PAL<->LibOS link; refuse rather than guess */
        return PAL_VBS_PK_RELTYPE;
    }
    if (s->st_shndx != SHN_UNDEF) {
        if (!in_image(o, s->st_value, 0)) {
            *detail = symidx;
            return PAL_VBS_PK_BADELF;
        }
        *value = (uint64_t)(uintptr_t)o->base + s->st_value;
        return PAL_VBS_PK_OK;
    }
    const char* name = str_at(o, s->st_name);
    if (!name) {
        *detail = symidx;
        return PAL_VBS_PK_BADELF;
    }
    for (uint64_t i = 0; i < nimp; i++) {
        if (strcmp(imp[i].name, name) == 0) {
            *value = (uint64_t)(uintptr_t)imp[i].addr;
            (*nbound)++;
            return PAL_VBS_PK_OK;
        }
    }
    if (bind == STB_WEAK) {
        *value = 0;
        return PAL_VBS_PK_OK;
    }
    *detail = symidx;
    return PAL_VBS_PK_UNDEF;
}

/*
 * Walk one relocation table. With apply == 0 only checks (no byte is written); with apply == 1
 * writes each target, which the check pass proved lies inside a writable segment.
 */
static int64_t do_relocs(struct pk_obj* o, uint64_t off, uint64_t sz, int apply,
                         const struct pal_vbs_import* imp, uint64_t nimp, uint64_t* count,
                         uint64_t* nbound, uint64_t* detail) {
    const vbs_elf64_rela* r = (const vbs_elf64_rela*)(o->base + off);
    uint64_t n = sz / sizeof(*r);
    for (uint64_t i = 0; i < n; i++) {
        uint32_t type = (uint32_t)(r[i].r_info & 0xffffffffu);
        uint64_t symidx = r[i].r_info >> 32;
        if (type == R_AARCH64_NONE)
            continue;
        if (!in_writable(o, r[i].r_offset, 8)) {
            *detail = r[i].r_offset;
            return PAL_VBS_PK_RELTARGET;
        }
        uint64_t value;
        switch (type) {
            case R_AARCH64_RELATIVE:
                value = (uint64_t)(uintptr_t)o->base + (uint64_t)r[i].r_addend;
                break;
            case R_AARCH64_ABS64:
            case R_AARCH64_GLOB_DAT:
            case R_AARCH64_JUMP_SLOT: {
                uint64_t s = 0, ignored = 0;
                int64_t ret = resolve_sym(o, symidx, imp, nimp, &s, apply ? &ignored : nbound,
                                          detail);
                if (ret < 0)
                    return ret;
                value = s + (uint64_t)r[i].r_addend; /* S + A for all three on AArch64 */
                break;
            }
            default:
                *detail = type;
                return PAL_VBS_PK_RELTYPE;
        }
        if (apply) {
            uint64_t* where = (uint64_t*)(o->base + r[i].r_offset);
            *where = value; /* the page was made RW in step 3; never an executable page */
        } else {
            (*count)++;
        }
    }
    return PAL_VBS_PK_OK;
}

/* ---- public interface ---- */

uint64_t pal_vbs_packed_count(void) {
    return PAL_VBS_PACKED_COUNT;
}

const char* pal_vbs_packed_name(uint64_t i) {
    return i < PAL_VBS_PACKED_COUNT ? g_pal_vbs_packed_objs[i].name : NULL;
}

const struct pal_vbs_packed_obj* pal_vbs_packed_table(uint64_t* count, uint64_t* blob_base,
                                                       uint64_t* blob_size, uint64_t* files_base,
                                                       uint64_t* files_size) {
    *count      = PAL_VBS_PACKED_COUNT;
    *blob_base  = (uint64_t)(uintptr_t)g_pal_vbs_packed_blob;
    *blob_size  = PAL_VBS_PACKED_BLOB_SIZE;
    *files_base = (uint64_t)(uintptr_t)g_pal_vbs_packed_files;
    *files_size = PAL_VBS_PACKED_FILES_SIZE;
    return g_pal_vbs_packed_objs;
}

int64_t pal_vbs_packed_load(const char* name, const struct pal_vbs_import* imports,
                            uint64_t nimports, struct pal_vbs_loaded* out, uint64_t* detail) {
    uint64_t dummy;
    if (!detail)
        detail = &dummy;
    *detail = 0;

    uint64_t idx = PAL_VBS_PACKED_COUNT;
    for (uint64_t i = 0; i < PAL_VBS_PACKED_COUNT; i++)
        if (strcmp(g_pal_vbs_packed_objs[i].name, name) == 0)
            idx = i;
    if (idx == PAL_VBS_PACKED_COUNT)
        return PAL_VBS_PK_NOTFOUND;
    if (g_loaded[idx])
        return PAL_VBS_PK_LOADED;

    struct pk_obj o;
    memset(&o, 0, sizeof(o));
    o.row  = &g_pal_vbs_packed_objs[idx];
    if (!o.row->image_size)
        return PAL_VBS_PK_NOTFOUND; /* a data-only packed file, not an ELF object */
    o.base = (uint8_t*)g_pal_vbs_packed_blob + o.row->image_offset;
    o.size = o.row->image_size;
    if (((uintptr_t)o.base & (VBS_PAGE - 1)) || (o.size & (VBS_PAGE - 1)))
        return PAL_VBS_PK_LAYOUT;

    /* steps 1 and 2: validate everything; nothing has been written yet */
    int64_t ret = parse_headers(&o, detail);
    if (ret < 0)
        return ret;
    ret = parse_dynamic(&o, detail);
    if (ret < 0)
        return ret;
    uint64_t nrela = 0, nbound = 0;
    ret = do_relocs(&o, o.rela, o.relasz, 0, imports, nimports, &nrela, &nbound, detail);
    if (ret < 0)
        return ret;
    ret = do_relocs(&o, o.jmprel, o.pltrelsz, 0, imports, nimports, &nrela, &nbound, detail);
    if (ret < 0)
        return ret;
    void* entry = NULL;
    if (o.row->entry_vaddr) {
        if (!in_executable(&o, o.row->entry_vaddr, 4)) {
            *detail = o.row->entry_vaddr;
            return PAL_VBS_PK_LAYOUT;
        }
        entry = o.base + o.row->entry_vaddr;
    }

    /* step 3: the object's writable segments become read-write (image pages: execute-read ->
     * read-write, the one-way change the platform permits). Nothing is written before every
     * range has been changed successfully. */
    for (uint64_t w = 0; w < o.nwr; w++) {
        uint64_t lo = page_down(o.wr_lo[w]), hi = page_up(o.wr_hi[w]);
        DWORD old = 0;
        if (!VirtualProtect(o.base + lo, (SIZE_T)(hi - lo), PAGE_READWRITE, &old)) {
            *detail = ((uint64_t)GetLastError() << 32) | lo;
            return PAL_VBS_PK_PROTECT;
        }
    }

    /* step 4: apply (cannot fail: the check pass resolved every entry) */
    do_relocs(&o, o.rela, o.relasz, 1, imports, nimports, &dummy, &dummy, detail);
    do_relocs(&o, o.jmprel, o.pltrelsz, 1, imports, nimports, &dummy, &dummy, detail);

    /* step 5: RELRO back to read-only. A failure leaves it read-write, which is safe (it is data)
     * but weaker; report it through nrelro == 0. */
    uint64_t nrelro = 0;
    if (o.relro_hi > o.relro_lo) {
        DWORD old = 0;
        if (VirtualProtect(o.base + o.relro_lo, (SIZE_T)(o.relro_hi - o.relro_lo), PAGE_READONLY,
                           &old))
            nrelro = (o.relro_hi - o.relro_lo) / VBS_PAGE;
    }

    g_loaded[idx] = 1;
    out->name     = o.row->name;
    out->base     = o.base;
    out->size     = o.size;
    out->entry    = entry;
    out->dynamic  = o.base + o.dyn_off;
    out->nrela    = nrela;
    out->nimports = nbound;
    out->nrelro   = nrelro;
    return PAL_VBS_PK_OK;
}

void* pal_vbs_packed_sym(const struct pal_vbs_loaded* obj, const char* sym) {
    for (uint64_t i = 0; i < PAL_VBS_PACKED_COUNT; i++) {
        const struct pal_vbs_packed_obj* row = &g_pal_vbs_packed_objs[i];
        if (!row->image_size || (uint8_t*)g_pal_vbs_packed_blob + row->image_offset != obj->base)
            continue;
        struct pk_obj o;
        uint64_t detail;
        memset(&o, 0, sizeof(o));
        o.row  = row;
        o.base = obj->base;
        o.size = obj->size;
        if (parse_headers(&o, &detail) < 0 || parse_dynamic(&o, &detail) < 0)
            return NULL;
        const vbs_elf64_sym* s = find_defined(&o, sym);
        return s ? o.base + s->st_value : NULL;
    }
    return NULL;
}
