"""
Generate syscall-entry wrappers that narrow every argument to its declared C type.

The syscall table calls each `libos_syscall_*` function with six full 64-bit registers. On RISC-V
the C calling convention lets a callee assume that a 32-bit argument (`int`, `unsigned int`,
`mode_t`, `uid_t`, ...) arrives sign-extended in its register, while the kernel syscall ABI makes
no such promise: glibc passes `uid_t -1` or an `_IOR` ioctl request zero-extended, and raw
`syscall()` callers may leave anything in the upper half. The compiled LibOS code then compares or
indexes with the wrong 64-bit value. The Linux kernel avoids this with SYSCALL_DEFINE, which casts
each `long` register to the declared type; this script does the same for the LibOS: for every
prototype in `libos_table.h` it emits

    static long libos_wrap_NAME(unsigned long a0, ..., unsigned long a5) {
        return (long)libos_syscall_NAME((T0)a0, (T1)a1, ...);
    }
    #define libos_syscall_NAME libos_wrap_NAME   (after all wrappers)

so that an architecture's syscall table, by including the output after `libos_table.h`, points at
the wrappers without any other change.

Usage: gen_syscall_wrappers.py <libos_table.h> <output.h> <defined macro>...
(the macros, e.g. __riscv, decide the header's `#ifdef` blocks)
"""

import re
import sys


def preprocess(text, defined):
    """Keep the lines of active #if/#ifdef/#else/#endif branches (the forms libos_table.h uses)."""
    out = []
    stack = []  # (this branch active, any branch taken)

    def active():
        return all(s[0] for s in stack)

    for line in text.splitlines():
        stripped = line.strip()
        m = re.match(r'#\s*(ifdef|ifndef|if|elif|else|endif)\b(.*)', stripped)
        if not m:
            if not stripped.startswith('#') and active():
                out.append(line)
            continue
        kind, rest = m.group(1), m.group(2).strip()
        if kind in ('ifdef', 'ifndef'):
            val = rest in defined
            val = val if kind == 'ifdef' else not val
            stack.append((val, val))
        elif kind == 'if':
            val = evaluate(rest, defined)
            stack.append((val, val))
        elif kind == 'elif':
            _, taken = stack.pop()
            val = not taken and evaluate(rest, defined)
            stack.append((val, taken or val))
        elif kind == 'else':
            _, taken = stack.pop()
            stack.append((not taken, True))
        else:
            stack.pop()
    if stack:
        raise SystemExit('unbalanced #if in the header')
    return '\n'.join(out)


def evaluate(expr, defined):
    py = re.sub(r'defined\s*\(\s*(\w+)\s*\)', lambda m: str(m.group(1) in defined), expr)
    py = py.replace('||', ' or ').replace('&&', ' and ').replace('!', ' not ')
    if not re.fullmatch(r'[\sTrueFalsnotad()]*', py):
        raise SystemExit(f'unsupported #if expression: {expr}')
    return bool(eval(py))  # pylint: disable=eval-used


def param_type(param):
    param = ' '.join(param.split())
    array = re.match(r'(.*?)\s*\b\w+\s*\[\s*\w*\s*\]$', param)
    if array:
        return array.group(1) + '*'
    m = re.match(r'(.*?[\s\*])(\w+)$', param)
    if not m:
        raise SystemExit(f'cannot parse parameter: {param}')
    return m.group(1).strip()


def main():
    header, output, *defined = sys.argv[1:]
    text = open(header, encoding='utf-8').read()
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    text = re.sub(r'//[^\n]*', '', text)
    text = preprocess(text, set(defined))

    protos = re.findall(r'([A-Za-z_][\w \*]*?)\s*\b(libos_syscall_\w+)\s*\(([^;{]*?)\)\s*;',
                        text, re.S)
    lines = [
        '/* Generated by libos/src/arch/gen_syscall_wrappers.py from libos_table.h: do not edit. */',
        '#pragma once',
        '',
    ]
    names = []
    for _ret, name, params in protos:
        params = params.strip()
        plist = [] if params in ('', 'void') else [p for p in params.split(',')]
        if len(plist) > 6:
            raise SystemExit(f'{name}: more than six arguments')
        types = [param_type(p) for p in plist]
        args = ', '.join(f'({t})a{i}' for i, t in enumerate(types))
        wrap = name.replace('libos_syscall_', 'libos_wrap_')
        sig = ', '.join(f'unsigned long a{i}' for i in range(6))
        unused = ''.join(f' (void)a{i};' for i in range(len(types), 6))
        lines.append(f'static __attribute__((unused)) long {wrap}({sig}) {{{unused}')
        lines.append(f'    return (long){name}({args});')
        lines.append('}')
        names.append((name, wrap))
    lines.append('')
    for name, wrap in names:
        lines.append(f'#define {name} {wrap}')
    lines.append('')
    open(output, 'w', encoding='utf-8').write('\n'.join(lines))


if __name__ == '__main__':
    main()
