"""Saguaro x64 phase-0 spike (step h): write the two PT_LOAD segments of app.elf into elf_blob.c as
arrays in an executable read-only section (.gxelft, padded to a fixed 64 KiB so that the image
layout does not depend on the program) and a writable section (.gxelfd); check that the program
needs no relocation; write the entry offsets of _start and _start_ms into elf_blob.h."""
TEXT_PAD = 0x10000
import struct, sys

elf = open(sys.argv[1], 'rb').read()
assert elf[:4] == b'\x7fELF' and elf[4] == 2 and struct.unpack_from('<H', elf, 18)[0] == 62, 'not ELF64 x86_64'
e_entry, e_phoff, e_shoff = struct.unpack_from('<QQQ', elf, 24)
e_phentsize, e_phnum, e_shentsize, e_shnum, e_shstrndx = struct.unpack_from('<HHHHH', elf, 54)
loads = []
for i in range(e_phnum):
    p_type, p_flags, p_offset, p_vaddr, _, p_filesz, p_memsz, _ = struct.unpack_from('<IIQQQQQQ', elf, e_phoff + i * e_phentsize)
    if p_type == 1:
        loads.append((p_flags, p_offset, p_vaddr, p_filesz, p_memsz))
    print(f'phdr type={p_type} flags={p_flags} off=0x{p_offset:x} vaddr=0x{p_vaddr:x} filesz=0x{p_filesz:x} memsz=0x{p_memsz:x}')
syms = {}
secs = [struct.unpack_from('<IIQQQQIIQQ', elf, e_shoff + i * e_shentsize) for i in range(e_shnum)]
for s in secs:
    assert s[1] not in (4, 9), 'the program has relocation sections'
    if s[1] == 2:   # SHT_SYMTAB
        strtab = secs[s[6]]
        for k in range(s[5] // 24):
            st_name, st_info, _, _, st_value, _ = struct.unpack_from('<IBBHQQ', elf, s[4] + k * 24)
            name = elf[strtab[4] + st_name:elf.index(b'\0', strtab[4] + st_name)].decode()
            syms[name] = st_value
assert len(loads) == 2, 'expected two PT_LOAD segments'
(tf, to, tv, tfs, tms), (df, do, dv, dfs, dms) = loads
assert tf == 5 and to == 0 and tv == 0 and df == 6, 'unexpected segment layout'
assert tfs <= TEXT_PAD
text = elf[0:tfs].ljust(TEXT_PAD, b'\0')
data = elf[do:do + dfs].ljust((dms + 4095) & ~4095, b'\0')
def arr(b):
    return ',\n'.join(','.join(str(x) for x in b[i:i + 32]) for i in range(0, len(b), 32))
with open('elf_blob.c', 'w') as f:
    f.write('/* generated by elfsplit.py from app.elf */\n'
            '#pragma section(".gxelft", read, execute)\n#pragma section(".gxelfd", read, write)\n'
            f'__declspec(allocate(".gxelft")) __declspec(align(4096)) const unsigned char gx_elf_text[{len(text)}] = {{\n{arr(text)}\n}};\n'
            f'__declspec(allocate(".gxelfd")) __declspec(align(4096)) unsigned char gx_elf_data[{len(data)}] = {{\n{arr(data)}\n}};\n')
with open('elf_blob.h', 'w') as f:
    f.write(f'#define ELF_START 0x{syms["_start"]:x}\n#define ELF_START_MS 0x{syms["_start_ms"]:x}\n#define ELF_DATA_ADDR 0x{dv:x}\n')
print(f'entry=0x{e_entry:x} _start=0x{syms["_start"]:x} _start_ms=0x{syms["_start_ms"]:x} text={TEXT_PAD} bytes data={len(data)} bytes at +0x{dv:x}')
